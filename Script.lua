-- 1. KONFIGURACJA WEBHOOKA
local DISCORD_WEBHOOK_URL = webhooka_discord -- Podmień na swój link z Discorda

local Players = game:GetService("Players")
local Workspace = game:GetService("Workspace")
local Lighting = game:GetService("Lighting")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local HttpService = game:GetService("HttpService")
local localPlayer = Players.LocalPlayer or Players:GetPlayers()[1]

-- Uniwersalna funkcja wysyłająca surowy JSON na Discord Webhook
local function sendRawDiscordWebhook(payloadTable: table)
	if DISCORD_WEBHOOK_URL == "Webhooka Discord" or DISCORD_WEBHOOK_URL == "" then
		warn("[MAGE LOG] No Discord Webhook URL configured!")
		return
	end

	local payload = HttpService:JSONEncode(payloadTable)

	local reqFunc = (syn and syn.request) or (http and http.request) or request or (http_request)
	
	if reqFunc then
		reqFunc({
			Url = DISCORD_WEBHOOK_URL,
			Method = "POST",
			Headers = { ["Content-Type"] = "application/json" },
			Body = payload
		})
		print("[F9 PUSH] Powiadomienie wysłane na Discord!")
	else
		pcall(function()
			HttpService:PostAsync(DISCORD_WEBHOOK_URL, payload, Enum.HttpContentType.ApplicationJson)
		end)
		print("[F9 PUSH] Powiadomienie wysłane przez HttpService!")
	end
end

-- 2. WIADOMOŚĆ STARTOWA (STARTUP WEBHOOK + COBALT NOTIFY)
local function sendStartupWebhook()
	local shiftText = "Unknown"
	local playerGui = localPlayer:FindFirstChild("PlayerGui")
	if playerGui then
		local shiftGui = playerGui:FindFirstChild("Shift")
		local frame = shiftGui and shiftGui:FindFirstChild("Frame")
		local header = frame and frame:FindFirstChild("header")
		local textObj = header and header:FindFirstChild("text") :: TextLabel?
		if textObj and (textObj:IsA("TextLabel") or textObj:IsA("TextBox")) then
			shiftText = textObj.Text ~= "" and textObj.Text or "Unknown"
		end
	end

	local coffeeReadyText = "no"
	local misc = Workspace:FindFirstChild("Misc")
	local coffeeMachine = misc and misc:FindFirstChild("CoffeeMachine")
	local attachment = coffeeMachine and coffeeMachine:FindFirstChild("Attachment")
	local ui = attachment and attachment:FindFirstChild("UI")
	local statusLabel = ui and ui:FindFirstChild("status") :: TextLabel?
	if statusLabel and statusLabel:IsA("TextLabel") then
		if string.find(string.lower(statusLabel.Text), "ready") then
			coffeeReadyText = "yes"
		end
	end

	local normalList = {}
	local anomalyList = {}

	local npcsFolder = Workspace:FindFirstChild("NPCs")
	if npcsFolder then
		for _, child in ipairs(npcsFolder:GetChildren()) do
			if child:IsA("Model") and child.Name ~= "Doctor" and child.Name ~= "Barney" then
				if child:GetAttribute("Skinwalker") ~= nil then
					table.insert(anomalyList, child.Name)
				else
					table.insert(normalList, child.Name)
				end
			end
		end
	end

	local normalsFormatted = #normalList > 0 and table.concat(normalList, ", ") or "0"
	local anomaliesFormatted = #anomalyList > 0 and table.concat(anomalyList, ", ") or "0"

	local descriptionText = string.format(
		"Now Shift is ``%s`` 🗓️\n\nThe coffee is ready. = ``%s``\n\nlist of NPCs:\nNormals: ``%s`` ✅\nAnomalies: ``%s`` ⚠️",
		shiftText,
		coffeeReadyText,
		normalsFormatted,
		anomaliesFormatted
	)

	sendRawDiscordWebhook({
		content = nil,
		embeds = {
			{
				description = descriptionText,
				color = nil
			}
		},
		attachments = {}
	})

	-- Dodany kod Cobalt po wysłaniu wiadomości startowej
	-- This code was generated by Cobalt
	-- https://gitlab.com/upio/cobalt
	local success, err = pcall(function()
		local Event = ReplicatedStorage.Util.Net["RE/Notify"]
		firesignal(Event.OnClientEvent, 
			"Thanks for use Script Animal Hospital Log Webhook Discord"
		)
	end)
	if not success then
		warn("[MAGE LOG] Nie udało się odpalić firesignal dla Cobalt Notify: " .. tostring(err))
	end
end

-- 3. WYKRYWANIE ZMIAN W KAMERACH (SecurityCamPC.screen.UI.Frame.cams)
local function setupSecurityCamerasListener()
	local misc = Workspace:WaitForChild("Misc", 5)
	if not misc then return end

	local securityCamPC = misc:WaitForChild("SecurityCamPC", 5)
	if not securityCamPC then return end

	local screen = securityCamPC:WaitForChild("screen", 5)
	if not screen then return end

	local ui = screen:WaitForChild("UI", 5)
	if not ui then return end

	local frame = ui:WaitForChild("Frame", 5)
	if not frame then return end

	local camsObj = frame:WaitForChild("cams", 5) :: TextLabel?
	if not camsObj or (not camsObj:IsA("TextLabel") and not camsObj:IsA("TextBox")) then return end

	local lastCamsText = camsObj.Text

	local function checkCamsText()
		local currentText = camsObj.Text
		if currentText ~= lastCamsText then
			lastCamsText = currentText
			sendRawDiscordWebhook({
				content = nil,
				embeds = {
					{
						title = currentText,
						color = nil
					}
				},
				attachments = {}
			})
		end
	end

	camsObj:GetPropertyChangedSignal("Text"):Connect(checkCamsText)
end

-- 4. WYKRYWANIE POZIOMU POCZYTALNOŚCI (Sanity)
local function setupSanityListener()
	local playerGui = localPlayer:WaitForChild("PlayerGui", 5) :: PlayerGui?
	if not playerGui then return end

	local sanityGui = playerGui:WaitForChild("Sanity", 5)
	if not sanityGui then return end

	local frame1 = sanityGui:WaitForChild("Frame", 5)
	local frame2 = frame1 and frame1:WaitForChild("Frame", 5)
	local textbox = frame2 and frame2:WaitForChild("textbox", 5)
	local amountLabel = textbox and textbox:WaitForChild("amount", 5) :: TextLabel?

	if not amountLabel or (not amountLabel:IsA("TextLabel") and not amountLabel:IsA("TextBox")) then return end

	local lastSanityText = ""

	local function checkSanity()
		local currentText = amountLabel.Text

		if currentText ~= lastSanityText then
			local emoji = ""
			local shouldSend = false

			if currentText == "100" then
				emoji = "🌕"
				shouldSend = true
			elseif currentText == "50" then
				emoji = "🌙"
				shouldSend = true
			elseif currentText == "10" then
				emoji = "☕"
				shouldSend = true
			elseif currentText == "5" then
				emoji = "🏃‍♂️‍➡️☕"
				shouldSend = true
			end

			if shouldSend then
				lastSanityText = currentText
				sendRawDiscordWebhook({
					content = nil,
					embeds = {
						{
							title = string.format("You Sanity = %s %s", currentText, emoji),
							color = nil
						}
					},
					attachments = {}
				})
			end
		end
	end

	checkSanity()
	amountLabel:GetPropertyChangedSignal("Text"):Connect(checkSanity)
end

-- 5. WYKRYWANIE STARTU / ZAKOŃCZENIA DESZCZU (Lighting["Rain (Chill)"])
local function setupRainEventListener()
	local isRainActive = false

	local function checkRainState(isInitialCheck: boolean?)
		local rainSky = Lighting:FindFirstChild("Rain (Chill)")

		if rainSky and not isRainActive then
			isRainActive = true
			sendRawDiscordWebhook({
				content = nil,
				embeds = {
					{
						title = "``Start`` event ``Rain``",
						color = nil
					}
				},
				attachments = {}
			})
		elseif not rainSky and isRainActive then
			isRainActive = false
			sendRawDiscordWebhook({
				content = nil,
				embeds = {
					{
						title = "``End`` event ``Rain``",
						color = nil
					}
				},
				attachments = {}
			})
		end
	end

	checkRainState(true)
	Lighting.ChildAdded:Connect(function(child: Instance)
		if child.Name == "Rain (Chill)" then checkRainState() end
	end)
	Lighting.ChildRemoved:Connect(function(child: Instance)
		if child.Name == "Rain (Chill)" then checkRainState() end
	end)
end

